// Look up photo and attribution for a model name or vehicle object
export function creditFor(vehicleOrName) {
  if (!vehicleOrName) return null;
  const name = typeof vehicleOrName === "string" 
    ? vehicleOrName 
    : (vehicleOrName.name || `${vehicleOrName.make || ""} ${vehicleOrName.model || ""}`).trim();
  
  if (PHOTO_CREDITS[name]) return PHOTO_CREDITS[name];
  
  // Try matching make + model
  if (typeof vehicleOrName === "object" && vehicleOrName.make && vehicleOrName.model) {
    const mm = `${vehicleOrName.make} ${vehicleOrName.model}`.trim();
    if (PHOTO_CREDITS[mm]) return PHOTO_CREDITS[mm];
  }
  
  // Fuzzy lookup on partial match
  const lower = name.toLowerCase();
  for (const [key, val] of Object.entries(PHOTO_CREDITS)) {
    if (lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) {
      return val;
    }
  }
  return null;
}

// Return photo URL if catalogued, otherwise ""
export function photoForModel(vehicleOrName) {
  const credit = creditFor(vehicleOrName);
  return credit ? credit.img : "";
}

// Format a clean HTML attribution line
export function formatCreditHtml(credit) {
  if (!credit || !credit.author) return "";
  const author = credit.author;
  const lic = credit.licence;
  const licUrl = credit.licenceUrl;
  const srcUrl = credit.sourceUrl;
  
  const authorPart = srcUrl 
    ? `<a href="${srcUrl}" target="_blank" rel="noopener noreferrer">${author}</a>`
    : author;
  const licPart = licUrl
    ? `<a href="${licUrl}" target="_blank" rel="noopener noreferrer">${lic}</a>`
    : lic;
    
  return `<span class="photo-credit">Photo: ${authorPart}, ${licPart}</span>`;
}
