import assert from 'node:assert/strict';
import { savingsPlan, addMonths } from '../js/savings.js';
import { prepareBulkSelection } from '../js/bulk-selection.js';
import { formatDate, formatMonth } from '../js/dates.js';
const today = new Date(2026, 9, 21, 12);
const p = savingsPlan({price:10000000,condition:'New',down:40,saved:1000000,income:500000,mode:'percent',contribution:20,fees:100000,insurance:200000,targetDate:'2027-10-21'},today);
assert.equal(p.downPct,60);
assert.equal(p.target,6300000);
assert.equal(p.monthly,100000);
assert.equal(p.months,53);
assert.equal(p.required,5300000/12);
assert.equal(p.percent,20);
assert.equal(savingsPlan({price:1e7,condition:'Used',down:40,saved:5e6,mode:'fixed',contribution:0},today).months,0);
assert.equal(savingsPlan({price:1e7,condition:'Used',down:40,mode:'fixed',contribution:0},today).months,null);
assert.equal(savingsPlan({price:1e7,condition:'Used',down:40,cash:true,mode:'fixed',contribution:1000},today).target,1e7);
assert.ok(savingsPlan({price:1e7,targetDate:'2026-10-20'},today).targetError);
assert.equal(savingsPlan({price:1e7,targetDate:'2027-02-30'},today).targetError,'Choose a valid target date.');
assert.equal(formatDate('2028-02-29'),'29 Feb 2028');
assert.equal(formatDate('2027-02-29'),'Date unavailable');
assert.equal(formatDate('2026-10-21',{numeric:true}),'21-10-2026');
assert.equal(formatDate('21/10/2026'),'21 Oct 2026');
assert.equal(formatMonth('2026-10'),'Oct 2026');
assert.equal(addMonths(new Date(2027,0,31),1).getDate(),28);
assert.equal(addMonths(new Date(2028,0,31),1).getDate(),29);
const cars=[{id:'a',price:100,name:'A'},{id:'b',price:null,name:'B'},{id:'a',price:100,name:'A again'},{id:'c',price:300,name:'C',priceBasis:'conflicting'},{id:'d',price:400,name:'D'}];
assert.deepEqual(prepareBulkSelection(cars,['a']).eligible.map(v=>v.id),['d']);
assert.deepEqual(prepareBulkSelection(cars).eligible.map(v=>v.id),['a','d']);
assert.equal(prepareBulkSelection(cars).skipped.length,2);
console.log('Savings goals, calendar boundaries and bulk selection checks passed');

const { dateInputValue } = await import('../js/date-picker.js');
assert.equal(dateInputValue('29-02-2028'), '2028-02-29');
assert.equal(dateInputValue('2028-02-29'), '2028-02-29');
assert.equal(dateInputValue('29-02-2027'), '29-02-2027');
assert.equal(dateInputValue('12-31-2027'), '12-31-2027');
assert.equal(dateInputValue(''), '');
